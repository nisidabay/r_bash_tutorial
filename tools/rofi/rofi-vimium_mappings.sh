#!/usr/bin/env bash
#
# Show Vimium keybindings
declare -a mappings
mappings=(
    "?: show help dialog"
    "h: scroll left"
    "j: scroll down"
    "k: scroll up"
    "l: scroll right"
    "gg: scroll to top"
    "G: scroll to bottom"
    "d: scroll down half page"
    "u: scroll up half page"
    "f: open link in current tab"
    "F: open link in new tab"
    "r: reload"
    "gs: view source"
    "i: enter insert mode"
    "yy: copy current url"
    "yf: copy link url"
    "gf: cycle forward to next frame"
    "gF: focus main/top frame"
    "o: open URL/bookmark/history"
    "O: open URL/bookmark/history in new tab"
    "b: open bookmark"
    "B: open bookmark in new tab"
    "/: enter find mode"
    "n: next find match"
    "N: previous find match"
    "H: go back in history"
    "L: go forward in history"
    "J: go one tab left"
    "K: go one tab right"
    "gT: go one tab left"
    "gt: go one tab right"
    "g0: go to first tab"
    "g$: go to last tab"
    "^: visit previous tab"
    "t: create tab"
    "yt: duplicate current tab"
    "x: close current tab"
    "X: restore closed tab"
    "T: search open tabs"
    "W: move tab to new window"
    "<a-p>: pin/unpin tab"
    "ma: set local mark a"
    "mA: set global mark A"
    "$(a: jump to local mark a"
    ")A: jump to global mark A"
    "$(): jump to previous position"
    "]], [[: follow next/previous links"
    "<a-f>: open multiple links in new tabs"
    "gi: focus first text input"
    "gu: go up URL hierarchy"
    "gU: go to URL root"
    "ge: edit current URL"
    "gE: edit URL in new tab"
    "zH: scroll all the way left"
    "zL: scroll all the way right"
    "v: enter visual mode"
    "V: enter visual line mode"
    "R: hard reload page"
)

# Use dmenu to display the list of qutebrowser keybindings
printf '%s\n' "${mappings[@]}" | rofi -dmenu -p "Vimium keybindings" | xclip -r -selection clipboard
notify-send "Vimium keybindings copied to clipboard"

